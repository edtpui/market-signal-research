"""The ptrade export bundle for one deployment: the files `python -m ptrade.new_model NAME --family basket` would
write, plus Strategy Lab's engine pinned by sha256 (as models/fdb_v5fam + ptrade/basket_pin.py pin research code).
It is written under Strategy Lab's own var/ directory; applying it to the operational repo is a human step after
approval (OPERATOR.md in the bundle). The tree mirrors paper_trading's:

  baskets/plugins/<module>.py          the plug-in (RULE, PRODUCER): import-safe, delegates to the pinned engine
  models/strategy_lab/PIN.json         sha256 of every pinned file
  models/strategy_lab/strategy_lab/... the engine modules that decide trades (core, engine, strategies, paper plug-in)
  models/strategy_lab/user/*.py        the deployment's user strategy module, if it is not built in
  config/books.entry.toml              the [[book]] entry to append to config/books.toml
  config/settings.patch.toml           the [paths] key for the Strategy Lab ledger
  docs/protocols/<book>.md             the pre-registration stub (model_id filled in)
  OPERATOR.md, MANIFEST.json
"""
