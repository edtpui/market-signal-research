def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def module_name(spec: DeploymentSpec) -> str:
    return "sl_" + spec.key()[:10]


def producer_config(spec: DeploymentSpec, pin_sha: str) -> dict:
    return dict(producer=f"{spec.book_id()}-universe", deployment=spec.key(), pin_sha256=pin_sha,
                universe_sha256=sha256_bytes(",".join(spec.universe).encode()))


def ptrade_model_id(book_id: str, params: dict, producer_cfg: dict, plugin_sha: str) -> str:
    """ptrade's model_id for a plug-in basket book: '<id>:1:<sha256 of BasketBook.config()>' (baskets/books.py),
    where the config carries the plug-in file's sha256 for both the rule and the producer."""
    cfg = dict(book=book_id, unit="index", rule=book_id, params=params, scores=producer_cfg,
               rule_source_sha256=plugin_sha, scores_source_sha256=plugin_sha)
    return f"{book_id}:1:{canonical_hash(cfg)}"


def lf(data: bytes) -> bytes:
    """The bundle is LF only (it runs on Linux, and its sha256s must not depend on the checkout's line endings)."""
    return data.replace(b"\r\n", b"\n")


def build(spec: DeploymentSpec, strategy_cls, out_dir: Path, validation: dict) -> dict:
    """Writes the bundle to out_dir (replaced if it exists: a bundle is derived, never a record) and returns its
    manifest."""
    out_dir = Path(out_dir)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    pkg = Path(strategy_lab.__file__).resolve().parent
    pin_root = out_dir / "models" / "strategy_lab"
    files = {}
    for rel in PINNED:
        src = pkg / rel
        dst = pin_root / "strategy_lab" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        data = lf(src.read_bytes())
        dst.write_bytes(data)
        files[f"strategy_lab/{rel}"] = sha256_bytes(data)
    if not strategy_cls.__module__.startswith("strategy_lab."):
        src = Path(inspect.getfile(strategy_cls))
        dst = pin_root / "user" / src.name
        dst.parent.mkdir(parents=True, exist_ok=True)
        data = lf(src.read_bytes())
        dst.write_bytes(data)
        files[f"user/{src.name}"] = sha256_bytes(data)
    pin = dict(engine="strategy_lab", version=strategy_lab.__version__, files=dict(sorted(files.items())))
    pin_bytes = (json.dumps(pin, indent=1, sort_keys=True) + "\n").encode()
    (pin_root / "PIN.json").write_bytes(pin_bytes)
    pin_sha = sha256_bytes(pin_bytes)

    book_id, mod = spec.book_id(), module_name(spec)
    pcfg = producer_config(spec, pin_sha)
    params = {"deployment": spec.key()[:16]}
    created = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    plugin_src = PLUGIN.format(book_id=book_id, name=spec.name.replace('"', "'") or book_id,
                               pin_sha=pin_sha, spec_json=spec.model_dump_json(),
                               producer_config=json.dumps(pcfg, sort_keys=True))
    plugin_path = out_dir / "baskets" / "plugins" / f"{mod}.py"
    plugin_path.parent.mkdir(parents=True, exist_ok=True)
    plugin_path.write_text(plugin_src, encoding="utf-8", newline="\n")
    plugin_sha = sha256_bytes(plugin_path.read_bytes())
    model_id = ptrade_model_id(book_id, params, pcfg, plugin_sha)

    cfg_dir = out_dir / "config"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    (cfg_dir / "books.entry.toml").write_text(ENTRY.format(book_id=book_id, display=(spec.name or book_id)
                                                           .replace('"', "'"), ledger_key=LEDGER_KEY,
                                                           param=params["deployment"]), encoding="utf-8", newline="\n")
    (cfg_dir / "settings.patch.toml").write_text(f'[paths]\n{LEDGER_KEY} = "{LEDGER_PATH}"\n', encoding="utf-8",
                                                 newline="\n")
    proto = out_dir / "docs" / "protocols" / f"{book_id}.md"
    proto.parent.mkdir(parents=True, exist_ok=True)
    proto.write_text(PROTOCOL.format(book_id=book_id, strategy=spec.strategy, version=spec.strategy_version,
                                     params=json.dumps(spec.params, sort_keys=True), model_id=model_id,
                                     n_universe=len(spec.universe), universe=", ".join(spec.universe),
                                     execution=spec.execution.model_dump_json(), capital=spec.initial_capital,
                                     engine_version=strategy_lab.__version__, pin_sha=pin_sha,
                                     start=spec.start_date.isoformat()), encoding="utf-8", newline="\n")
    job = out_dir / "scripts" / JOB_SCRIPT.name
    job.parent.mkdir(parents=True, exist_ok=True)
    job.write_bytes(lf(JOB_SCRIPT.read_bytes()))
    from strategy_lab.paper.contract import SOURCE_COMMIT
    (out_dir / "OPERATOR.md").write_text(OPERATOR.format(book_id=book_id, commit=SOURCE_COMMIT, module=mod,
                                                         ledger_key=LEDGER_KEY, ledger_path=LEDGER_PATH,
                                                         model_id=model_id), encoding="utf-8", newline="\n")
    manifest = dict(book_id=book_id, module=mod, model_id=model_id, deployment_key=spec.key(), pin_sha256=pin_sha,
                    plugin_sha256=plugin_sha, params=params, created_utc=created, spec=spec.model_dump(mode="json"),
                    validation=validation, applied=False,
                    files={p.relative_to(out_dir).as_posix(): sha256_bytes(p.read_bytes())
                           for p in sorted(out_dir.rglob("*")) if p.is_file()})
    (out_dir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, sort_keys=True), encoding="utf-8",
                                           newline="\n")
    return manifest
